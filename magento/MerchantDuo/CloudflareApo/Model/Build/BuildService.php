<?php
declare(strict_types=1);

namespace MerchantDuo\CloudflareApo\Model\Build;

use Magento\Framework\Component\ComponentRegistrarInterface;
use Magento\Framework\Exception\LocalizedException;
use Magento\Framework\Filesystem\DirectoryList;
use MerchantDuo\CloudflareApo\Api\BuildServiceInterface;
use MerchantDuo\CloudflareApo\Model\Config\Settings;
use MerchantDuo\CloudflareApo\Model\Support\CanonicalJson;
use Symfony\Component\Process\Process;

class BuildService implements BuildServiceInterface
{
    private const MAX_OUTPUT_LENGTH = 65536;

    public function __construct(
        private ProjectConfigFactory $configFactory,
        private CanonicalJson $json,
        private DirectoryList $directories,
        private ComponentRegistrarInterface $componentRegistrar,
        private Settings $settings
    ) {
    }

    /** @return array<string, mixed> */
    public function build(int $websiteId = 0): array
    {
        if ($this->settings->value('deployment/mode', $websiteId) !== 'local') {
            throw new LocalizedException(__('Cloudflare Workers Builds is not supported. Select Local Node.js.'));
        }

        $config = $this->configFactory->create($websiteId);
        $configJson = $this->json->encode($config);
        $sourceHash = $this->hashDirectory($this->sourceDirectory());
        $buildHash = hash('sha256', $sourceHash . "\n" . $configJson);
        $workspace = $this->directories->getPath(DirectoryList::VAR_DIR) . '/merchantduo-cloudflare-apo/build/' . $websiteId . '/' . $buildHash;
        $reportPath = $workspace . '/build-report.json';
        if (is_file($reportPath)) {
            $report = json_decode((string) file_get_contents($reportPath), true);
            if (is_array($report) && ($report['state'] ?? '') === 'complete') {
                return $report;
            }
        }

        $this->copyDirectory($this->sourceDirectory(), $workspace);
        $generated = $workspace . '/src/generated/project-config.ts';
        file_put_contents($generated, "/** Generated by Magento. Do not edit. */\nexport const projectConfig = " . $configJson . " as const;\n");

        $output = '';
        try {
            $this->run(['node', '--version'], $workspace, $output);
            $this->run(['npm', 'ci', '--ignore-scripts'], $workspace, $output);
            $this->run(['npm', 'run', 'check'], $workspace, $output);
            $this->run(['npx', 'wrangler', 'deploy', '--dry-run', '--outdir', 'dist'], $workspace, $output);
        } catch (\Throwable $exception) {
            $report = $this->report($websiteId, $buildHash, $sourceHash, $config, 'failed', $output, $exception->getMessage(), $workspace);
            file_put_contents($reportPath, $this->json->encode($report));
            throw new LocalizedException(__('Worker build failed. See %1.', $reportPath));
        }

        $report = $this->report($websiteId, $buildHash, $sourceHash, $config, 'complete', $output, '', $workspace);
        file_put_contents($reportPath, $this->json->encode($report));
        return $report;
    }

    private function sourceDirectory(): string
    {
        $modulePath = $this->componentRegistrar->getPath(ComponentRegistrarInterface::MODULE, 'MerchantDuo_CloudflareApo');
        $packagePath = dirname($modulePath, 3);
        if (!is_file($packagePath . '/package.json') || !is_file($packagePath . '/wrangler.jsonc') || !is_file($packagePath . '/src/index.ts')) {
            throw new LocalizedException(__('The Cloudflare APO package Worker source is unavailable. Install the module through Composer.'));
        }

        return $packagePath;
    }

    private function run(array $command, string $workspace, string &$output): void
    {
        $process = new Process($command, $workspace, ['npm_config_cache' => $this->directories->getPath(DirectoryList::VAR_DIR) . '/merchantduo-cloudflare-apo/npm-cache']);
        $process->setTimeout(300);
        $process->run();
        $output .= "$ " . implode(' ', $command) . "\n" . $process->getOutput() . $process->getErrorOutput();
        $output = mb_substr($output, -self::MAX_OUTPUT_LENGTH);
        if (!$process->isSuccessful()) {
            throw new \RuntimeException('Command failed with exit code ' . $process->getExitCode());
        }
    }

    private function copyDirectory(string $source, string $destination): void
    {
        if (!is_dir($destination)) {
            mkdir($destination, 0700, true);
        }
        $iterator = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($source, \FilesystemIterator::SKIP_DOTS), \RecursiveIteratorIterator::SELF_FIRST);
        foreach ($iterator as $item) {
            $relative = substr($item->getPathname(), strlen($source) + 1);
            if (str_starts_with($relative, 'node_modules/') || $relative === 'node_modules') {
                continue;
            }
            $target = $destination . '/' . $relative;
            if ($item->isDir()) {
                if (!is_dir($target)) {
                    mkdir($target, 0700, true);
                }
            } elseif ($item->isFile()) {
                copy($item->getPathname(), $target);
            }
        }
    }

    private function hashDirectory(string $directory): string
    {
        $files = [];
        $iterator = new \RecursiveIteratorIterator(new \RecursiveDirectoryIterator($directory, \FilesystemIterator::SKIP_DOTS));
        foreach ($iterator as $item) {
            if ($item->isFile() && !str_starts_with(substr($item->getPathname(), strlen($directory) + 1), 'node_modules/')) {
                $files[] = $item->getPathname();
            }
        }
        sort($files, SORT_STRING);
        $hash = hash_init('sha256');
        foreach ($files as $file) {
            hash_update($hash, substr($file, strlen($directory) + 1) . "\0");
            hash_update_file($hash, $file);
        }
        return hash_final($hash);
    }

    /** @return array<string, mixed> */
    private function report(int $websiteId, string $buildHash, string $sourceHash, array $config, string $state, string $output, string $error = '', string $workspace = ''): array
    {
        return ['websiteId' => $websiteId, 'buildHash' => $buildHash, 'sourceHash' => $sourceHash, 'configHash' => hash('sha256', $this->json->encode($config)), 'workspace' => $workspace, 'state' => $state, 'createdAt' => gmdate(DATE_ATOM), 'output' => mb_substr($output, -self::MAX_OUTPUT_LENGTH), 'error' => $error];
    }
}
